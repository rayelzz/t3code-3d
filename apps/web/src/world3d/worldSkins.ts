/** 将任意 T3 Code 主题 ID 归一化到对应的 3D 世界装潢皮肤 */
export function resolveWorldSkinId(themePreference: string): WorldSkinId {
  const normalized = themePreference.toLowerCase();
  if (normalized.includes("grove") || normalized.includes("forest")) return "grove";
  if (normalized.includes("ember") || normalized.includes("sunset") || normalized.includes("warm"))
    return "ember";
  if (normalized.includes("iris") || normalized.includes("violet") || normalized.includes("purple"))
    return "iris";
  if (normalized.includes("t3-chat") || normalized.includes("rose") || normalized.includes("pink"))
    return "t3-chat";
  return "ocean";
}

